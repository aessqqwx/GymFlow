package com.aess.gymflow

import java.time.DayOfWeek

private fun ex(
    id: String,
    muscle: String,
    title: String,
    sets: Int,
    rest: Int,
    vararg cues: String
) = Exercise(
    id = id,
    muscle = muscle,
    title = title,
    sets = sets,
    restSec = rest,
    cues = cues.toList(),
    reps = when {
        id.contains("warmup") -> "5–7 мин"
        id.contains("stretch") -> "30–60 сек"
        id.contains("core") -> "10–15 / 30–60 сек"
        id.contains("calf") || id.contains("tib") -> "12–15"
        else -> "8–12"
    },
    weightLabel = when {
        id.contains("warmup") || id.contains("stretch") || id.contains("core") -> null
        else -> "Рабочий вес"
    }
)

